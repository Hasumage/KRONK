export function documentIntent(raw: string, hasFileReply = false): boolean {
  const text = raw
    .toLocaleLowerCase()
    .replace(/ё/g, 'е')
    .replace(/«[^»]*»|“[^”]*”|"[^"]*"/gu, '')
    .trim();
  // A clear leading "гляну" authorizes analysis; the rest is the owner's focus,
  // including phrases such as "почему не надо" or "как организовать задачи".
  if (hasFileReply) {
    const leading = text.match(
      /^(?:(?:ок|окей|хорошо|ладно|да|я)[,\s]+)*(?:гляну|глянь|изучу|изучи|изучим|посмотрю|посмотри|прочитаю|прочитай|почитаю|почитай|разберу|разбери|разберусь|проверю|проверь|проанализирую|проанализируй|резюмируй|суммируй|ознакомлюсь|заценю|зацени|чекну|чекни|погляжу|погляди)(?!\p{L})/iu,
    );
    if (
      leading &&
      !/^[,\s—-]*(?:если|когда|возможно|наверное)(?!\p{L})/iu.test(text.slice(leading[0].length))
    )
      return true;
  }
  if (
    /(?<!\p{L})не\s+(?:буду|надо|нужно|хочу|изуч|посмотр|смотр|гля|разбир|разбер|анализ|провер|чита|проч|дела|ознаком|зацен|чек|погляд)/iu.test(
      text,
    )
  )
    return false;
  if (/задач|таск|календар/iu.test(text)) return false;
  if (/(?<!\p{L})(?:если|возможно|наверное)(?!\p{L})|может\s+быть/iu.test(text)) return false;
  const topic =
    /документ|договор|контракт|соглашени|услови|оферт|файл|презентаци|отчет|отчёт|инструкци|текст|pdf|docx/iu.test(
      text,
    );
  if (!topic && !hasFileReply) return false;
  return /(?<!\p{L})(?:изучу|изучи|изучим|посмотрю|посмотри|гляну|глянь|прочитаю|прочитай|почитаю|почитай|разберу|разбери|разберусь|проверю|проверь|проанализирую|проанализируй|резюмируй|суммируй|ознакомлюсь|заценю|зацени|чекну|чекни|погляжу|погляди)(?!\p{L})|(?:надо|нужно|хочу|давай)\s+(?:изучить|посмотреть|почитать|прочитать|разобрать|проанализировать)|(?:сделай|сделаю|подготовь|дай)\s+(?:краткую\s+)?(?:выжимку|разбор|резюме)/iu.test(
    text,
  );
}
