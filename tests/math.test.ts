import { describe, it, expect } from 'vitest';
import { solveMath } from '../src/services/math.js';

describe('Математические примеры без eval и нейросети', () => {
  it.each([
    ['125 × 48', '6000'],
    ['2+2', '4'],
    ['(12 + 8) / 5', '4'],
    ['0,1 + 0,2', '0.3'],
    ['2^10', '1024'],
    ['2**10', '1024'],
    ['-2^2', '-4'],
    ['(-2)^2', '4'],
    ['2^3^2', '512'],
    ['2^-3', '0.125'],
    ['10/3', '≈ 3.33'],
    ['2/3', '≈ 0.67'],
    ['-2/3', '≈ -0.67'],
    ['1/8', '0.125'],
    ['(300000000000-1)/300000000000', '≈ 1'],
    ['1/(3*10^20)', '≈ 0'],
    ['1/10^40', '≈ 0'],
    ['1/128', '≈ 0.00781'],
    ['1/256', '≈ 0.00391'],
    ['1/100000', '0.00001'],
    ['0.000005*1', '≈ 0.00001'],
    ['-0.000005*1', '≈ -0.00001'],
    ['-0.000004*1', '≈ 0'],
    ['0.999999*1', '≈ 1'],
    ['1/3+1/6', '0.5'],
    ['100000000000000000+1', '100000000000000001'],
    ['Посчитай: 25 х 4?', '100'],
    ['сколько будет 6 ÷ 4?', '1.5'],
    ['Реши пример: 12:3=', '4'],
    ['10% от 250', '25'],
    ['50%*20', '10'],
    ['2−8', '-6'],
    ['2--3', '5'],
  ])('%s → %s', (expression, answer) =>
    expect(solveMath(expression)).toEqual({ kind: 'answer', text: answer }),
  );
  it.each([
    'Привет!',
    'Сколько стоит доставка?',
    '123456789',
    '+79991234567',
    '8 (999) 123-45-67',
    '2026-10-25',
    '25.10.2026',
    '18:30',
    '2+2=4',
    'process.exit()',
    '2+fetch("https://evil.org")',
    '<script>2+2</script>',
    '2 3 + 1',
  ])('игнорирует нематематический ввод: %s', (text) =>
    expect(solveMath(text)).toEqual({ kind: 'ignore' }),
  );
  it.each([
    '1/0',
    '0^-1',
    '(2+3',
    '2^10000',
    '2^0.5',
    '1..2+3',
    '((((((((((((((((((((((((((((((((((2+2))))))))))))))))))))))))))))))))))',
  ])('ошибка ограничена и не приводит к выполнению кода: %s', (text) =>
    expect(solveMath(text).kind).toBe('error'),
  );
  it('ограничивает длину и сложность', () => {
    expect(solveMath('2+'.repeat(300) + '2').kind).toBe('ignore');
    expect(solveMath('1+'.repeat(100) + '1').kind).toBe('ignore');
  });
});
