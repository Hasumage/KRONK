import { describe, it, expect } from 'vitest';
import { hasCalendarCommitment } from '../src/domain/calendar-intent.js';
describe('Маркер разрешения на создание события', () => {
  it.each([
    'Хорошо, буду, занесу в календарь',
    'Внесу себе эту встречу в календарь',
    'Добавлю в календарь',
    'Запишу себе в расписание',
    'Не забуду занести в календарь',
    'Запланирую встречу',
    'Ок, закину в календарь',
    'Щас забью в календарь',
    'Ага, вобью в календарик',
    'Добавлю себе в расписание',
    'Поставлю напоминалку',
    'Впишу себе',
    'Ладно, впишу у себя',
    'Запишу себе',
    'Отмечу у себя',
    'Помечу себе',
    'Зафиксирую у себя',
    'Черкну себе',
    'Забью встречу',
    'Зафиксирую этот созвон',
    'Окей, забьём время',
  ])('разрешает передать в семантический анализ: %s', (text) =>
    expect(hasCalendarCommitment(text)).toBe(true),
  );
  it.each([
    'Да, буду',
    'Хорошо',
    'Нет, не смогу, занесу в календарь',
    'Не добавляй в календарь',
    'Не хочу заносить в календарь',
    'Календарь открыт',
    'Не буду вносить встречу в календарь',
    'Я написал «занесу в календарь», а ничего не произошло',
    'Он сказал "занесу в календарь"',
    'Ок, буду',
    'Уже добавил в календарь',
    'Он добавит в календарь',
    'Не закидывай в календарь',
    'Не впишу себе',
    'Не хочу забить встречу',
    'Забью на встречу',
    'Забей на календарь',
    'Запишу себе номер телефона',
    'Отмечу у себя в задачах',
    'Зафиксирую себе адрес',
    'Впишусь в историю',
    'У себя посмотрю',
  ])('не разрешает: %s', (text) => expect(hasCalendarCommitment(text)).toBe(false));
});
